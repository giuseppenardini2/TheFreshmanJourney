package com.thefreshmanjourney.model.game.character.movement;

/**
 * This enum represents the possible directions of a movable game object.
 */
public enum Direction {

    /**
     * The singleton up direction.
     */
    UP,

    /**
     * The singleton down direction.
     */
    DOWN,

    /**
     * The singleton left direction.
     */
    LEFT,

    /**
     * The singleton right direction.
     */
    RIGHT;

}
