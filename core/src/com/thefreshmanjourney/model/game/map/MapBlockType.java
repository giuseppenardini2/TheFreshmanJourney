package com.thefreshmanjourney.model.game.map;

/**
 * This enum represents the types of map blocks.
 */
public enum MapBlockType {

    /**
     * The singleton wall map block.
     */
    WALL,

    /**
     * The singleton desk map block.
     */
    DESK,

    /**
     * The singleton tile map block.
     */
    TILE,

    /**
     * The singleton junk map block.
     */
    JUNK,

    /**
     * The singleton exit map block.
     */
    EXIT;

}
