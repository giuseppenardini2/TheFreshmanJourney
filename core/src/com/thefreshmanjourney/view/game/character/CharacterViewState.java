package com.thefreshmanjourney.view.game.character;

/**
 * This enums represents the character view state.
 */
public enum CharacterViewState {

    /**
     * The singleton quiet character view state.
     */
    QUIET,

    /**
     * The singleton up character view state.
     */
    UP,

    /**
     * The singleton down character view state.
     */
    DOWN,

    /**
     * The singleton left character view state.
     */
    LEFT,

    /**
     * The singleton right character view state.
     */
    RIGHT,

    /**
     * The singleton dead character view state.
     */
    DEAD;

}
